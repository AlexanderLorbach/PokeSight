import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * Generates the generation-specific ruleset YAML files from the PokeAPI CSV dump.
 *
 * <p>Usage: {@code java tools/GenerateRuleset.java <generation> <outputDir>}
 * <br>Example: {@code java tools/GenerateRuleset.java 4 src/main/resources/rulesets/gen4}
 *
 * <p>Writes {@code type-chart.yaml}, {@code pokemon.yaml} and {@code moves.yaml}.
 */
public class GenerateRuleset {

    private static final String CSV_BASE = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/";
    private static final String HEADER = "# Generated by tools/GenerateRuleset.java from PokeAPI (https://pokeapi.co) - do not edit by hand.\n";
    /** PokeAPI language ids for the languages the app supports. */
    private static final Map<String, String> LANGUAGES = Map.of("EN", "9", "DE", "6");
    private static final int FIRST_NON_STANDARD_TYPE_ID = 10000;
    /** Ids from here on are Shadow moves of Colosseum / XD. */
    private static final int FIRST_NON_MAIN_SERIES_MOVE_ID = 10000;
    private static final String ARCEUS = "493";
    private static final int ARCEUS_UNKNOWN_FORM_GEN4 = 9;
    /** PokeAPI damage classes; status moves (1) never deal damage. */
    private static final Map<String, String> DAMAGE_CLASSES = Map.of("2", "PHYSICAL", "3", "SPECIAL");
    /**
     * Moves PokeAPI lists with a nominal power although it varies: Hidden Power (237, type and power depend on the
     * user) and Punishment (386, grows with the target's stat boosts). Found by cross-checking with Pokémon Showdown.
     */
    private static final List<String> VARIABLE_POWER_MOVES = List.of("237", "386");
    /** Luster Purge (295) had 70 power until Gen 6 (95 since Gen 7); PokeAPI's changelog lacks this (Showdown gen6 mod). */
    private static final String LUSTER_PURGE = "295";
    private static final int LUSTER_PURGE_OLD_POWER_UNTIL = 6;

    private final HttpClient http = HttpClient.newHttpClient();
    private final int generation;

    private GenerateRuleset(int generation) {
        this.generation = generation;
    }

    public static void main(String[] args) throws Exception {
        if (args.length != 2) {
            System.err.println("Usage: java tools/GenerateRuleset.java <generation> <outputDir>");
            System.exit(1);
        }
        int generation = Integer.parseInt(args[0]);
        Path outputDir = Path.of(args[1]);
        Files.createDirectories(outputDir);

        GenerateRuleset generator = new GenerateRuleset(generation);
        Map<String, String> typeKeys = generator.typeKeys();
        Files.writeString(outputDir.resolve("type-chart.yaml"), generator.typeChartYaml(typeKeys), StandardCharsets.UTF_8);
        Files.writeString(outputDir.resolve("pokemon.yaml"), generator.pokemonYaml(typeKeys), StandardCharsets.UTF_8);
        Files.writeString(outputDir.resolve("moves.yaml"), generator.movesYaml(typeKeys), StandardCharsets.UTF_8);
        System.out.println("Ruleset for generation " + generation + " written to " + outputDir.toAbsolutePath());
    }

    /** Type id -> enum key (e.g. "10" -> "FIRE") for every type that exists in this generation. */
    private Map<String, String> typeKeys() throws IOException, InterruptedException {
        Map<String, String> keys = new TreeMap<>(Comparator.comparingInt(Integer::parseInt));
        for (Map<String, String> row : csv("types")) {
            int id = Integer.parseInt(row.get("id"));
            if (id < FIRST_NON_STANDARD_TYPE_ID && Integer.parseInt(row.get("generation_id")) <= generation) {
                keys.put(row.get("id"), row.get("identifier").toUpperCase());
            }
        }
        return keys;
    }

    private String typeChartYaml(Map<String, String> typeKeys) throws IOException, InterruptedException {
        // Current chart first, then roll back every pair that changed after this generation.
        Map<String, String> factors = new HashMap<>();
        for (Map<String, String> row : csv("type_efficacy")) {
            factors.put(row.get("damage_type_id") + ">" + row.get("target_type_id"), row.get("damage_factor"));
        }
        // A past row is valid up to and including its generation_id; the oldest one still >= our generation wins.
        Map<String, Integer> pastGeneration = new HashMap<>();
        for (Map<String, String> row : csv("type_efficacy_past")) {
            int validUntil = Integer.parseInt(row.get("generation_id"));
            String pair = row.get("damage_type_id") + ">" + row.get("target_type_id");
            if (validUntil >= generation && validUntil < pastGeneration.getOrDefault(pair, Integer.MAX_VALUE)) {
                pastGeneration.put(pair, validUntil);
                factors.put(pair, row.get("damage_factor"));
            }
        }

        StringBuilder yaml = new StringBuilder(HEADER);
        yaml.append("# effectiveness: attacking type -> defending type -> multiplier. Pairs not listed are 1x.\n");
        yaml.append("types:\n");
        Map<String, Map<String, String>> typeNames = names("type_names", "type_id", "name");
        for (Map.Entry<String, String> type : typeKeys.entrySet()) {
            yaml.append("  ").append(type.getValue()).append(": ").append(nameMap(typeNames.get(type.getKey()))).append('\n');
        }
        yaml.append("effectiveness:\n");
        for (Map.Entry<String, String> attacker : typeKeys.entrySet()) {
            List<String> entries = new ArrayList<>();
            for (Map.Entry<String, String> defender : typeKeys.entrySet()) {
                String factor = factors.getOrDefault(attacker.getKey() + ">" + defender.getKey(), "100");
                if (!factor.equals("100")) {
                    entries.add(defender.getValue() + ": " + multiplier(factor));
                }
            }
            yaml.append("  ").append(attacker.getValue()).append(": { ").append(String.join(", ", entries)).append(" }\n");
        }
        return yaml.toString();
    }

    private String pokemonYaml(Map<String, String> typeKeys) throws IOException, InterruptedException {
        Map<String, String> defaultPokemonBySpecies = new HashMap<>();
        for (Map<String, String> row : csv("pokemon")) {
            if (row.get("is_default").equals("1")) {
                defaultPokemonBySpecies.put(row.get("species_id"), row.get("id"));
            }
        }
        Map<String, List<String>> currentTypes = types(csv("pokemon_types"), "pokemon_id");
        Map<String, List<String>> pastTypes = pastTypes();
        Map<String, List<String>> formOnlyTypes = types(csv("pokemon_form_types"), "pokemon_form_id");
        Map<String, List<Map<String, String>>> formsBySpecies = formsBySpecies();
        Map<String, Map<String, String>> speciesNames = names("pokemon_species_names", "pokemon_species_id", "name");
        Map<String, Map<String, String>> formNames = names("pokemon_form_names", "pokemon_form_id", "pokemon_name");

        StringBuilder yaml = new StringBuilder(HEADER);
        yaml.append("# Key: national dex number.\n");
        yaml.append("# forms: form index as stored in the game's data; only forms whose types differ from the base form.\n");
        yaml.append("# sprite: PokeAPI sprite file name of a form (the base form's sprite is its national dex number).\n");
        yaml.append("pokemon:\n");
        for (Map<String, String> species : csv("pokemon_species")) {
            if (Integer.parseInt(species.get("generation_id")) > generation) {
                continue;
            }
            String speciesId = species.get("id");
            String pokemonId = defaultPokemonBySpecies.get(speciesId);
            List<String> typeIds = pastTypes.getOrDefault(pokemonId, currentTypes.get(pokemonId));

            List<String> formLines = new ArrayList<>();
            List<Map<String, String>> forms = formsBySpecies.getOrDefault(speciesId, List.of());
            if (!forms.isEmpty() && !forms.getFirst().get("pokemon_id").equals(pokemonId)) {
                throw new IllegalStateException("Form 0 of species " + speciesId + " is not its default Pokemon");
            }
            for (int index = 1; index < forms.size(); index++) {
                Map<String, String> form = forms.get(index);
                String formPokemonId = form.get("pokemon_id");
                List<String> formTypeIds = formOnlyTypes.getOrDefault(form.get("id"),
                        pastTypes.getOrDefault(formPokemonId, currentTypes.get(formPokemonId)));
                // Same types as the base form, or the typeless ??? Arceus that no type chart covers.
                if (formTypeIds.equals(typeIds) || formTypeIds.stream().anyMatch(id -> Integer.parseInt(id) >= FIRST_NON_STANDARD_TYPE_ID)) {
                    continue;
                }
                // PokeAPI sprite file names: forms with their own Pokemon entry use its id (Sandy Wormadam: 10004),
                // forms of the same entry use "<species>-<form>" (Fire Arceus: 493-fire).
                String sprite = formPokemonId.equals(pokemonId) ? speciesId + "-" + form.get("form_identifier") : formPokemonId;
                formLines.add("      " + index + ": { name: " + nameMap(formNames.get(form.get("id")))
                        + ", types: " + typeList(typeKeys, formTypeIds, speciesId) + ", sprite: " + quote(sprite) + " }\n");
            }

            String name = nameMap(speciesNames.get(speciesId));
            String types = typeList(typeKeys, typeIds, speciesId);
            if (formLines.isEmpty()) {
                yaml.append("  ").append(speciesId).append(": { name: ").append(name).append(", types: ").append(types).append(" }\n");
            } else {
                yaml.append("  ").append(speciesId).append(":\n")
                        .append("    name: ").append(name).append('\n')
                        .append("    types: ").append(types).append('\n')
                        .append("    forms:\n");
                formLines.forEach(yaml::append);
            }
        }
        return yaml.toString();
    }

    /**
     * Damaging moves of this generation with the type and power they had then. PokeAPI's changelog rows hold the
     * values a move had before a version group changed them, so for every change after this generation's last
     * version group the earliest such row gives the value of that time (e.g. Thunderbolt: 95, 90 since Gen 6).
     * Moves without a fixed power (Low Kick, Seismic Toss, ...) are left out: they cannot be ranked by power.
     */
    private String movesYaml(Map<String, String> typeKeys) throws IOException, InterruptedException {
        Map<String, Integer> versionGroupOrder = new HashMap<>();
        int lastOrderOfGeneration = Integer.MIN_VALUE;
        for (Map<String, String> group : csv("version_groups")) {
            int order = Integer.parseInt(group.get("order"));
            versionGroupOrder.put(group.get("id"), order);
            if (Integer.parseInt(group.get("generation_id")) == generation) {
                lastOrderOfGeneration = Math.max(lastOrderOfGeneration, order);
            }
        }
        Map<String, Map<String, String>> pastValues = new HashMap<>();
        Map<String, Integer> pastOrder = new HashMap<>();
        for (Map<String, String> change : csv("move_changelog")) {
            int changedAt = versionGroupOrder.get(change.get("changed_in_version_group_id"));
            if (changedAt <= lastOrderOfGeneration) {
                continue;
            }
            for (String field : List.of("type_id", "power")) {
                String key = change.get("move_id") + "/" + field;
                if (!change.get(field).isEmpty() && changedAt < pastOrder.getOrDefault(key, Integer.MAX_VALUE)) {
                    pastOrder.put(key, changedAt);
                    pastValues.computeIfAbsent(change.get("move_id"), k -> new HashMap<>()).put(field, change.get(field));
                }
            }
        }

        Map<String, Map<String, String>> moveNames = names("move_names", "move_id", "name");
        StringBuilder yaml = new StringBuilder(HEADER);
        yaml.append("# Damaging moves with a fixed power, as they were in this generation. Key: move id.\n");
        yaml.append("moves:\n");
        for (Map<String, String> move : csv("moves")) {
            String category = DAMAGE_CLASSES.get(move.get("damage_class_id"));
            boolean mainSeries = Integer.parseInt(move.get("id")) < FIRST_NON_MAIN_SERIES_MOVE_ID;
            if (!mainSeries || Integer.parseInt(move.get("generation_id")) > generation || category == null) {
                continue;
            }
            Map<String, String> past = pastValues.getOrDefault(move.get("id"), Map.of());
            String power = past.getOrDefault("power", move.get("power"));
            String typeId = past.getOrDefault("type_id", move.get("type_id"));
            if (power.isEmpty() || VARIABLE_POWER_MOVES.contains(move.get("id"))) {
                continue;
            }
            if (move.get("id").equals(LUSTER_PURGE) && generation <= LUSTER_PURGE_OLD_POWER_UNTIL) {
                power = "70";
            }
            yaml.append("  ").append(move.get("id")).append(": { name: ").append(nameMap(moveNames.get(move.get("id"))))
                    .append(", type: ").append(typeList(typeKeys, List.of(typeId), "move " + move.get("id")).replaceAll("[\\[\\]]", ""))
                    .append(", power: ").append(power).append(", category: ").append(category).append(" }\n");
        }
        return yaml.toString();
    }

    /**
     * Forms that are stored in a Pokemon's data, by species id, in the game's form index order.
     * Battle-only forms (Castform's weather forms, Cherrim) and Megas never appear in stored data.
     */
    private Map<String, List<Map<String, String>>> formsBySpecies() throws IOException, InterruptedException {
        Map<String, String> speciesByPokemon = new HashMap<>();
        csv("pokemon").forEach(row -> speciesByPokemon.put(row.get("id"), row.get("species_id")));
        Map<String, Integer> generationByVersionGroup = new HashMap<>();
        csv("version_groups").forEach(row -> generationByVersionGroup.put(row.get("id"), Integer.parseInt(row.get("generation_id"))));

        Map<String, List<Map<String, String>>> forms = new HashMap<>();
        for (Map<String, String> form : csv("pokemon_forms")) {
            if (generationByVersionGroup.get(form.get("introduced_in_version_group_id")) <= generation
                    && form.get("is_battle_only").equals("0") && form.get("is_mega").equals("0")) {
                forms.computeIfAbsent(speciesByPokemon.get(form.get("pokemon_id")), k -> new ArrayList<>()).add(form);
            }
        }
        forms.values().forEach(list -> list.sort(Comparator.comparingInt(form -> Integer.parseInt(form.get("form_order")))));

        // PokeAPI lists Arceus' ??? form last. Gen 4 stores it at index 9, between Steel and Fire;
        // later games dropped it. See PKHeX FormItem.GetFormArceusPlate.
        List<Map<String, String>> arceus = forms.get(ARCEUS);
        if (arceus != null) {
            Map<String, String> unknown = arceus.stream().filter(form -> form.get("identifier").equals("arceus-unknown")).findFirst().orElseThrow();
            arceus.remove(unknown);
            if (generation == 4) {
                arceus.add(ARCEUS_UNKNOWN_FORM_GEN4, unknown);
            }
        }
        return forms;
    }

    /** Types a Pokemon had in this generation if they changed later (e.g. Clefairy: Normal before Fairy existed). */
    private Map<String, List<String>> pastTypes() throws IOException, InterruptedException {
        Map<String, Integer> chosenGeneration = new HashMap<>();
        Map<String, List<Map<String, String>>> rowsByPokemon = new HashMap<>();
        for (Map<String, String> row : csv("pokemon_types_past")) {
            int validUntil = Integer.parseInt(row.get("generation_id"));
            String pokemonId = row.get("pokemon_id");
            int current = chosenGeneration.getOrDefault(pokemonId, Integer.MAX_VALUE);
            if (validUntil < generation || validUntil > current) {
                continue;
            }
            if (validUntil < current) {
                chosenGeneration.put(pokemonId, validUntil);
                rowsByPokemon.put(pokemonId, new ArrayList<>());
            }
            rowsByPokemon.get(pokemonId).add(row);
        }
        Map<String, List<String>> result = new HashMap<>();
        rowsByPokemon.forEach((pokemonId, rows) -> result.put(pokemonId, types(rows, "pokemon_id").get(pokemonId)));
        return result;
    }

    /** id -> type ids in slot order, for rows of pokemon_types, pokemon_types_past or pokemon_form_types. */
    private static Map<String, List<String>> types(List<Map<String, String>> rows, String idColumn) {
        Map<String, List<Map<String, String>>> grouped = new HashMap<>();
        rows.forEach(row -> grouped.computeIfAbsent(row.get(idColumn), k -> new ArrayList<>()).add(row));
        Map<String, List<String>> result = new HashMap<>();
        grouped.forEach((id, typeRows) -> result.put(id, typeRows.stream()
                .sorted(Comparator.comparingInt(row -> Integer.parseInt(row.get("slot"))))
                .map(row -> row.get("type_id"))
                .toList()));
        return result;
    }

    private static String typeList(Map<String, String> typeKeys, List<String> typeIds, String owner) {
        List<String> keys = new ArrayList<>();
        for (String typeId : typeIds) {
            String key = typeKeys.get(typeId);
            if (key == null) {
                throw new IllegalStateException(owner + " has type " + typeId + " which does not exist in this generation");
            }
            keys.add(key);
        }
        return "[" + String.join(", ", keys) + "]";
    }

    /** id -> (language key -> name) for the supported languages. Blank names count as missing. */
    private Map<String, Map<String, String>> names(String file, String idColumn, String nameColumn) throws IOException, InterruptedException {
        Map<String, String> languageKeys = new HashMap<>();
        LANGUAGES.forEach((key, pokeApiId) -> languageKeys.put(pokeApiId, key));
        Map<String, Map<String, String>> names = new HashMap<>();
        for (Map<String, String> row : csv(file)) {
            String language = languageKeys.get(row.get("local_language_id"));
            if (language != null && !row.get(nameColumn).isBlank()) {
                names.computeIfAbsent(row.get(idColumn), k -> new TreeMap<>()).put(language, row.get(nameColumn));
            }
        }
        return names;
    }

    private static String nameMap(Map<String, String> names) {
        if (names == null || !names.keySet().containsAll(LANGUAGES.keySet())) {
            throw new IllegalStateException("Missing translations: " + names);
        }
        List<String> entries = new ArrayList<>();
        names.forEach((language, name) -> entries.add(language + ": " + quote(name)));
        return "{ " + String.join(", ", entries) + " }";
    }

    private static String multiplier(String damageFactor) {
        return switch (damageFactor) {
            case "0" -> "0";
            case "50" -> "0.5";
            case "200" -> "2";
            default -> throw new IllegalStateException("Unexpected damage factor " + damageFactor);
        };
    }

    private static String quote(String value) {
        return '"' + value.replace("\\", "\\\\").replace("\"", "\\\"") + '"';
    }

    private final Map<String, List<Map<String, String>>> downloaded = new HashMap<>();

    /** Downloads a PokeAPI CSV file once per run. */
    private List<Map<String, String>> csv(String name) throws IOException, InterruptedException {
        List<Map<String, String>> cached = downloaded.get(name);
        if (cached != null) {
            return cached;
        }
        HttpRequest request = HttpRequest.newBuilder(URI.create(CSV_BASE + name + ".csv")).build();
        HttpResponse<String> response = http.send(request, HttpResponse.BodyHandlers.ofString(StandardCharsets.UTF_8));
        if (response.statusCode() != 200) {
            throw new IOException("Download of " + name + ".csv failed with HTTP " + response.statusCode());
        }
        List<String> lines = response.body().lines().filter(line -> !line.isBlank()).toList();
        List<String> header = parseCsvLine(lines.getFirst());
        List<Map<String, String>> rows = new ArrayList<>();
        for (String line : lines.subList(1, lines.size())) {
            List<String> values = parseCsvLine(line);
            Map<String, String> row = new HashMap<>();
            for (int i = 0; i < header.size(); i++) {
                row.put(header.get(i), i < values.size() ? values.get(i) : "");
            }
            rows.add(row);
        }
        downloaded.put(name, rows);
        return rows;
    }

    /** Minimal RFC 4180 line parser; PokeAPI quotes fields that contain commas. */
    private static List<String> parseCsvLine(String line) {
        List<String> values = new ArrayList<>();
        StringBuilder current = new StringBuilder();
        boolean quoted = false;
        for (int i = 0; i < line.length(); i++) {
            char c = line.charAt(i);
            if (quoted && c == '"' && i + 1 < line.length() && line.charAt(i + 1) == '"') {
                current.append('"');
                i++;
            } else if (c == '"') {
                quoted = !quoted;
            } else if (c == ',' && !quoted) {
                values.add(current.toString());
                current.setLength(0);
            } else {
                current.append(c);
            }
        }
        values.add(current.toString());
        return values;
    }
}
