import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;

/**
 * Generates the learnset files (which damaging moves each Pokémon learns, and how) from the PokeAPI CSV dump, one per
 * game: learnsets differ between games of the same generation (Platinum's tutors, HeartGold's TMs).
 *
 * <p>Usage: {@code java tools/GenerateLearnsets.java <outputDir>}
 * <br>Example: {@code java tools/GenerateLearnsets.java src/main/resources/learnsets}
 *
 * <p>Writes {@code <id>.yaml} for every entry of {@link #GAMES}. Only damaging moves are written: the app knows no
 * others. Moves without a fixed power are written too; the app leaves out what its ruleset does not know.
 */
public class GenerateLearnsets {

    private static final String CSV_BASE = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/";
    private static final String HEADER = "# Generated by tools/GenerateLearnsets.java from PokeAPI (https://pokeapi.co) - do not edit by hand.\n";
    /**
     * File id -> PokeAPI version groups. The first one holds the learnsets; the others only add TM labels (the DLCs of
     * Sword/Shield and Scarlet/Violet brought new TMs, PokeAPI lists who learns them under the main game).
     */
    private static final Map<String, List<String>> GAMES = games();
    /** PokeAPI move learn methods kept: level-up, egg, tutor, machine and (Scarlet/Violet, Legends: Z-A) reminder. */
    private static final Map<String, String> METHODS = Map.of("1", "level", "2", "egg", "3", "tutor", "4", "machine", "13", "reminder");
    private static final List<String> LIST_METHODS = List.of("machine", "tutor", "egg", "reminder");
    /** PokeAPI damage classes of damaging moves: physical and special. */
    private static final Set<String> DAMAGING = Set.of("2", "3");
    /** Ids from here on are Shadow moves of Colosseum / XD. */
    private static final int FIRST_NON_MAIN_SERIES_MOVE_ID = 10000;

    private final HttpClient http = HttpClient.newHttpClient();
    private final Map<String, List<Map<String, String>>> downloaded = new HashMap<>();

    public static void main(String[] args) throws Exception {
        if (args.length != 1) {
            System.err.println("Usage: java tools/GenerateLearnsets.java <outputDir>");
            System.exit(1);
        }
        Path outputDir = Path.of(args[0]);
        Files.createDirectories(outputDir);
        GenerateLearnsets generator = new GenerateLearnsets();
        for (Map.Entry<String, List<String>> game : GAMES.entrySet()) {
            String yaml = generator.learnsetsYaml(game.getValue());
            Files.writeString(outputDir.resolve(game.getKey() + ".yaml"), yaml, StandardCharsets.UTF_8);
            System.out.println(game.getKey() + ": " + yaml.length() / 1024 + " KB");
        }
    }

    private static Map<String, List<String>> games() {
        Map<String, List<String>> games = new LinkedHashMap<>();
        for (String group : List.of("red-blue", "yellow", "gold-silver", "crystal", "ruby-sapphire", "emerald",
                "firered-leafgreen", "diamond-pearl", "platinum", "heartgold-soulsilver", "black-white", "black-2-white-2",
                "x-y", "omega-ruby-alpha-sapphire", "sun-moon", "ultra-sun-ultra-moon", "lets-go-pikachu-lets-go-eevee",
                "brilliant-diamond-shining-pearl", "legends-arceus", "legends-za")) {
            games.put(group, List.of(group));
        }
        games.put("sword-shield", List.of("sword-shield", "the-isle-of-armor", "the-crown-tundra"));
        games.put("scarlet-violet", List.of("scarlet-violet", "the-teal-mask", "the-indigo-disk"));
        return games;
    }

    private String learnsetsYaml(List<String> versionGroups) throws IOException, InterruptedException {
        Map<String, Map<String, String>> groups = new HashMap<>();
        csv("version_groups").forEach(row -> groups.put(row.get("identifier"), row));
        List<String> groupIds = versionGroups.stream().map(identifier -> Objects.requireNonNull(groups.get(identifier),
                () -> "Unknown PokeAPI version group: " + identifier).get("id")).toList();
        String learnsetGroup = groupIds.getFirst();

        Set<String> damaging = new TreeSet<>();
        for (Map<String, String> move : csv("moves")) {
            if (DAMAGING.contains(move.get("damage_class_id")) && Integer.parseInt(move.get("id")) < FIRST_NON_MAIN_SERIES_MOVE_ID) {
                damaging.add(move.get("id"));
            }
        }

        // Pokemon id -> its learnset in the main version group.
        Map<String, Learnset> byPokemon = new HashMap<>();
        for (Map<String, String> row : csv("pokemon_moves")) {
            String method = METHODS.get(row.get("pokemon_move_method_id"));
            if (method == null || !row.get("version_group_id").equals(learnsetGroup) || !damaging.contains(row.get("move_id"))) {
                continue;
            }
            Learnset learnset = byPokemon.computeIfAbsent(row.get("pokemon_id"), id -> new Learnset());
            int moveId = Integer.parseInt(row.get("move_id"));
            if (method.equals("level")) {
                learnset.level.merge(moveId, Integer.parseInt(row.get("level")), Math::min);
            } else {
                learnset.lists.computeIfAbsent(method, key -> new TreeSet<>()).add(moveId);
            }
        }

        StringBuilder yaml = new StringBuilder(HEADER);
        yaml.append("# Damaging moves each Pokémon learns in ").append(String.join(", ", versionGroups)).append(".\n");
        yaml.append("# machines: move id -> the TM / HM / TR that teaches it.\n");
        yaml.append("# pokemon: key national dex number; level: move id -> level (0: when it evolves); machine, tutor, egg,\n");
        yaml.append("# reminder (only from the move reminder): move ids; forms: form index -> a form's own learnset.\n");
        yaml.append("machines: {").append(String.join(", ", machines(groupIds, damaging))).append("}\n");
        yaml.append("pokemon:\n");
        Map<String, String> defaultPokemon = new HashMap<>();
        csv("pokemon").stream().filter(row -> row.get("is_default").equals("1"))
                .forEach(row -> defaultPokemon.put(row.get("species_id"), row.get("id")));
        Map<String, List<String>> formPokemon = formPokemonBySpecies(Integer.parseInt(groups.get(versionGroups.getFirst()).get("order")));
        List<String> speciesIds = new ArrayList<>(defaultPokemon.keySet());
        speciesIds.sort(Comparator.comparingInt(Integer::parseInt));
        for (String speciesId : speciesIds) {
            Learnset own = byPokemon.get(defaultPokemon.get(speciesId));
            List<String> forms = new ArrayList<>();
            List<String> pokemonIds = formPokemon.getOrDefault(speciesId, List.of());
            for (int index = 1; index < pokemonIds.size(); index++) {
                Learnset form = byPokemon.get(pokemonIds.get(index));
                // Forms of the same Pokemon entry (Unown, Arceus) and forms that learn the same share the species' set.
                if (form != null && !pokemonIds.get(index).equals(defaultPokemon.get(speciesId)) && !form.equals(own)) {
                    forms.add(index + ": " + form.yaml());
                }
            }
            if (own == null && forms.isEmpty()) {
                continue; // not in this game
            }
            List<String> parts = own == null ? new ArrayList<>() : own.parts();
            if (!forms.isEmpty()) {
                parts.add("forms: { " + String.join(", ", forms) + " }");
            }
            String entry = "{ " + String.join(", ", parts) + " }";
            yaml.append("  ").append(speciesId).append(": ").append(entry).append('\n');
        }
        return yaml.toString();
    }

    /** "move id: TM26" for every damaging move a machine of these version groups teaches; the first group wins. */
    private List<String> machines(List<String> groupIds, Set<String> damaging) throws IOException, InterruptedException {
        Map<String, String> itemNames = new HashMap<>();
        csv("items").forEach(row -> itemNames.put(row.get("id"), row.get("identifier").toUpperCase()));
        Map<Integer, String> labels = new TreeMap<>();
        for (String groupId : groupIds) {
            for (Map<String, String> row : csv("machines")) {
                if (row.get("version_group_id").equals(groupId) && damaging.contains(row.get("move_id"))) {
                    labels.putIfAbsent(Integer.parseInt(row.get("move_id")), itemNames.get(row.get("item_id")));
                }
            }
        }
        return labels.entrySet().stream().map(entry -> entry.getKey() + ": " + entry.getValue()).toList();
    }

    /**
     * Species id -> Pokemon id of each stored form, in the game's form index order (as tools/GenerateRuleset.java
     * numbers forms): battle-only forms, Megas and Totems never are in a team.
     */
    private Map<String, List<String>> formPokemonBySpecies(int lastOrder) throws IOException, InterruptedException {
        Map<String, String> speciesByPokemon = new HashMap<>();
        csv("pokemon").forEach(row -> speciesByPokemon.put(row.get("id"), row.get("species_id")));
        Map<String, Integer> groupOrder = new HashMap<>();
        csv("version_groups").forEach(row -> groupOrder.put(row.get("id"), Integer.parseInt(row.get("order"))));
        Map<String, List<Map<String, String>>> forms = new HashMap<>();
        for (Map<String, String> form : csv("pokemon_forms")) {
            if (groupOrder.get(form.get("introduced_in_version_group_id")) <= lastOrder
                    && form.get("is_battle_only").equals("0") && form.get("is_mega").equals("0")
                    && !form.get("form_identifier").contains("totem")) {
                forms.computeIfAbsent(speciesByPokemon.get(form.get("pokemon_id")), key -> new ArrayList<>()).add(form);
            }
        }
        Map<String, List<String>> result = new HashMap<>();
        forms.forEach((species, list) -> result.put(species, list.stream()
                .sorted(Comparator.comparingInt(form -> Integer.parseInt(form.get("form_order"))))
                .map(form -> form.get("pokemon_id"))
                .toList()));
        return result;
    }

    /** One Pokémon's damaging moves by learn method. */
    private static final class Learnset {
        final Map<Integer, Integer> level = new TreeMap<>();
        final Map<String, TreeSet<Integer>> lists = new TreeMap<>();

        String yaml() {
            List<String> parts = parts();
            return parts.isEmpty() ? "{}" : "{ " + String.join(", ", parts) + " }";
        }

        /** "level: {...}", "machine: [...]" and so on, for the methods it has. */
        List<String> parts() {
            List<String> parts = new ArrayList<>();
            if (!level.isEmpty()) {
                List<Map.Entry<Integer, Integer>> byLevel = new ArrayList<>(level.entrySet());
                byLevel.sort(Map.Entry.<Integer, Integer>comparingByValue().thenComparing(Map.Entry.comparingByKey()));
                parts.add("level: {" + String.join(", ", byLevel.stream().map(entry -> entry.getKey() + ": " + entry.getValue()).toList()) + "}");
            }
            for (String method : LIST_METHODS) {
                TreeSet<Integer> moves = lists.get(method);
                if (moves != null) {
                    parts.add(method + ": " + moves.toString().replace(" ", ""));
                }
            }
            return parts;
        }

        @Override
        public boolean equals(Object other) {
            return other instanceof Learnset that && level.equals(that.level) && lists.equals(that.lists);
        }

        @Override
        public int hashCode() {
            return Objects.hash(level, lists);
        }
    }

    /** Downloads a PokeAPI CSV file once per run. */
    private List<Map<String, String>> csv(String name) throws IOException, InterruptedException {
        List<Map<String, String>> cached = downloaded.get(name);
        if (cached != null) {
            return cached;
        }
        HttpRequest request = HttpRequest.newBuilder(URI.create(CSV_BASE + name + ".csv")).build();
        HttpResponse<String> response = http.send(request, HttpResponse.BodyHandlers.ofString(StandardCharsets.UTF_8));
        if (response.statusCode() != 200) {
            throw new IOException("Download of " + name + ".csv failed with HTTP " + response.statusCode());
        }
        List<String> lines = response.body().lines().filter(line -> !line.isBlank()).toList();
        List<String> header = parseCsvLine(lines.getFirst());
        List<Map<String, String>> rows = new ArrayList<>();
        for (String line : lines.subList(1, lines.size())) {
            List<String> values = parseCsvLine(line);
            Map<String, String> row = new HashMap<>();
            for (int i = 0; i < header.size(); i++) {
                row.put(header.get(i), i < values.size() ? values.get(i) : "");
            }
            rows.add(row);
        }
        downloaded.put(name, rows);
        return rows;
    }

    /** Minimal RFC 4180 line parser; PokeAPI quotes fields that contain commas. */
    private static List<String> parseCsvLine(String line) {
        List<String> values = new ArrayList<>();
        StringBuilder current = new StringBuilder();
        boolean quoted = false;
        for (int i = 0; i < line.length(); i++) {
            char c = line.charAt(i);
            if (quoted && c == '"' && i + 1 < line.length() && line.charAt(i + 1) == '"') {
                current.append('"');
                i++;
            } else if (c == '"') {
                quoted = !quoted;
            } else if (c == ',' && !quoted) {
                values.add(current.toString());
                current.setLength(0);
            } else {
                current.append(c);
            }
        }
        values.add(current.toString());
        return values;
    }
}
