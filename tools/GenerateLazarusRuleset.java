import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.regex.Pattern;

/**
 * Generates the ruleset of Pokémon Lazarus (Emerald hack by Nemo622, v2.0). The hack is binary-only (no source code,
 * no data sheet), so the ruleset follows what its documentation states:
 *
 * <ul>
 *   <li>Engine: pokeemerald-expansion (developer's documentation, credits "Feature Branches" of the expansion). The
 *       expansion's default data are the current main series games' (Gen 9 types, stats, abilities, moves, type chart):
 *       {@code tools/GeneratePokeemeraldRuleset.java} on Emerald Rogue EX (expansion defaults) gives the gen9 reference's
 *       types (Hisuian Goodra's order aside), stats, abilities, moves and type chart. So the reference is taken as it is.</li>
 *   <li>Changes in the changelogs (pokemonlazarus.net "Full Changelog", demo 1.0 to v2.0) that matter for matchups:
 *       none. Mega Evolutions and their types/abilities (Mega Raichu X Electric/Fighting, Mega Heliolisk Electric/Fire,
 *       ...) are battle-only forms, which PokeSight leaves out; Piscivore (Vaporeon) only speeds up fishing; Flower Gift
 *       summoning sun, Slam's priority and learnset changes do not change a type matchup or a move's power.</li>
 *   <li>Names: in-game names in mixed case, full length (expansion 1.9+ allows 12 letters; Lazarus started in 2025),
 *       English only.</li>
 *   <li>Roster: the Ilios Pokédex has 400+ Pokémon, but the expansion ROM holds all 1025 and trainers are not limited to
 *       the wild encounter tables, so all species stay in.</li>
 * </ul>
 *
 * <p>Usage: {@code java tools/GenerateLazarusRuleset.java src/main/resources/rulesets/gen9 src/main/resources/rulesets/lazarus}
 */
public class GenerateLazarusRuleset {

    private static final List<String> FILES = List.of("type-chart.yaml", "pokemon.yaml", "moves.yaml", "abilities.yaml");
    /** The German names of the reference: the hack is English only. */
    private static final Pattern GERMAN_NAME = Pattern.compile("DE: \"(?:[^\"\\\\]|\\\\.)*\", ");
    private static final String HEADER = """
            # Generated by tools/GenerateLazarusRuleset.java - do not edit by hand. Pokémon Lazarus (Nemo622, v2.0) runs on
            # pokeemerald-expansion with its default (Gen 9) data; its changelogs change no matchup outside battle-only Mega
            # Evolutions (see the generator). Data: the gen9 reference ruleset (from PokeAPI), English names only.
            """;

    public static void main(String[] args) throws IOException {
        if (args.length != 2) {
            System.err.println("Usage: java tools/GenerateLazarusRuleset.java <gen9 ruleset> <outputDir>");
            System.exit(1);
        }
        Path reference = Path.of(args[0]);
        Path output = Path.of(args[1]);
        Files.createDirectories(output);
        for (String file : FILES) {
            List<String> lines = Files.readAllLines(reference.resolve(file), StandardCharsets.UTF_8);
            StringBuilder yaml = new StringBuilder(HEADER);
            for (String line : lines) {
                if (line.startsWith("# Generated by")) {
                    continue; // the reference's own header line; its other comments still describe the format
                }
                String english = GERMAN_NAME.matcher(line).replaceAll("");
                if (english.contains("DE: ")) {
                    throw new IllegalStateException("German name left in " + file + ": " + line);
                }
                yaml.append(english).append('\n');
            }
            Files.writeString(output.resolve(file), yaml.toString(), StandardCharsets.UTF_8);
        }
        System.out.println("Ruleset written to " + output.toAbsolutePath());
    }
}
